export const useLanguage = create<LanguageStore>()(
  persist(
    (set, get) => ({
      lang: 'vi',
      setLang: (lang) => set({ lang }),
      t: (key) => {
        const { lang } = get();
        return (translations[lang] as any)[key] || key;
      },
    }),
    {
      name: 'language-storage',
    }
  )
);
